import type { SettingsState } from "@/shared/stores/settings";
import type { Category } from "./components/settings-categories";

type Nested =
  | "editor"
  | "terminal"
  | "ai"
  | "workspace"
  | "statusbar"
  | "mcp"
  | "lsp"
  | "experimental"
  | "agent"
  | "notifications"
  | "appearance"
  | "repositoryColors";

type GroupKey<K extends Nested> = `${K}.${Extract<keyof SettingsState[K], string>}`;

/** A stored value: `group.field` for grouped settings, the plain name for top-level ones. */
export type SettingKey =
  | { [K in Nested]: GroupKey<K> }[Nested]
  | Exclude<keyof SettingsState, Nested>;

/** Global settings apply everywhere; project settings can be overridden in .pragma/settings.json. */
export type SettingScope = "global" | "project";

export interface SettingDefinition {
  id: string;
  /** The stored values this setting reads and writes. */
  keys: SettingKey[];
  /** The label exactly as the settings page shows it. */
  label: string;
  /** A longer name for search results, when the label alone is ambiguous. */
  searchLabel?: string;
  description: string;
  keywords: string;
  category: Category;
  scope: SettingScope;
  /** The source file that applies the setting; it must mention the last part of each key. */
  effect: string;
}

